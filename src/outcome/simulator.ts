import type { DatabaseSync } from 'node:sqlite';
import type { DemoContext, RevisionPayload, ScenarioId } from '../review/types.js';
import { ReviewError } from '../review/types.js';
import { hash } from '../review/proposal.js';
import { transaction } from '../review/database.js';
import type { SimulatedResult, SimulatorMode } from './types.js';

export function simulatorMode(value: unknown): SimulatorMode {
  if (!['accepted', 'rejected', 'accepted_timeout', 'unknown_timeout'].includes(String(value))) throw new ReviewError(422, 'Choose a supported simulator outcome.');
  return value as SimulatorMode;
}
interface ProviderRow { request_hash: string; mode: SimulatorMode; provider_reference: string | null; lookup_supported: number; submissions: number }
const accepted = (reference: string): SimulatedResult => ({ state: 'accepted', providerReference: reference,
  explanation: 'Simulated provider accepted this request. This does not confirm fan delivery.' });

/** Local SQLite-backed provider double. No network implementation exists. */
export class MessagingSimulator {
  constructor(private db: DatabaseSync, private context: DemoContext) {}
  send(id: ScenarioId, key: string, payload: RevisionPayload, mode: SimulatorMode, evaluationAt: string): SimulatedResult {
    const p = payload.proposal;
    if (!p || (p.channel === 'email' ? !p.recipient.destination.endsWith('@example.invalid') : !p.recipient.destination.startsWith('synthetic-token:'))) {
      return { state: 'failed', providerReference: null, explanation: 'Simulator rejected before acceptance: only explicit example.invalid email or synthetic-token push destinations are allowed.' };
    }
    return transaction(this.db, () => {
      const existing = this.db.prepare('SELECT * FROM simulated_provider_requests WHERE tenant_id = ? AND scenario_id = ? AND idempotency_key = ?')
        .get(this.context.tenantId, id, key) as unknown as ProviderRow | undefined;
      if (existing && existing.request_hash !== hash(payload)) throw new Error('An idempotency key cannot authorize a different request snapshot');
      if (existing?.provider_reference) return accepted(existing.provider_reference);
      if (existing && !existing.lookup_supported) return { state: 'unknown', providerReference: null, explanation: 'The simulator has insufficient provider evidence. Investigate; do not retry or change channel/key.' };
      const reference = mode === 'accepted' || mode === 'accepted_timeout' ? `SIM-${p.channel}-${hash(key).slice(0, 14)}` : null;
      this.db.prepare(`INSERT INTO simulated_provider_requests VALUES (?, ?, ?, ?, ?, ?, ?, 1, ?)
        ON CONFLICT (tenant_id, scenario_id, idempotency_key) DO UPDATE SET mode = excluded.mode,
        provider_reference = excluded.provider_reference, lookup_supported = excluded.lookup_supported, submissions = submissions + 1`)
        .run(this.context.tenantId, id, key, hash(payload), mode, reference, mode === 'unknown_timeout' ? 0 : 1, evaluationAt);
      if (mode === 'accepted') return accepted(reference!);
      if (mode === 'rejected') return { state: 'failed', providerReference: null, explanation: 'Simulated provider definitely rejected before acceptance. A single explicit retry is permitted after fresh checks.' };
      return { state: 'unknown', providerReference: null, explanation: mode === 'accepted_timeout'
        ? 'Simulated response lost after the provider may have accepted. Reconcile with the stable request key; do not retry.'
        : 'Simulated timeout with no sufficient provider evidence. Outcome unknown; investigate without retrying.' };
    });
  }
  lookup(id: ScenarioId, key: string): SimulatedResult {
    const record = this.db.prepare('SELECT * FROM simulated_provider_requests WHERE tenant_id = ? AND scenario_id = ? AND idempotency_key = ?')
      .get(this.context.tenantId, id, key) as unknown as ProviderRow | undefined;
    if (!record || !record.lookup_supported) return { state: 'unknown', providerReference: null,
      explanation: 'No sufficient provider lookup evidence is available. Remain unknown and investigate; no new request was made.' };
    if (record.provider_reference) return accepted(record.provider_reference);
    return { state: 'failed', providerReference: null, explanation: 'Simulated status lookup establishes rejection before acceptance. No message was generated by reconciliation.' };
  }
}
